{{ config(materialized='table') }}
-- Converted from GOLD.SP_BUILD_PATIENT_360.
with converted_result (PATIENT_ID, PATIENT_NAME, AGE, GENDER, TOTAL_ENCOUNTERS, TOTAL_DIAGNOSES, TOTAL_PROCEDURES, TOTAL_MEDICATIONS, TOTAL_CLAIM_AMOUNT, TOTAL_APPROVED_AMOUNT, LAST_ENCOUNTER_DATE, RISK_SCORE, REFRESHED_AT) as (
WITH E AS (
 SELECT PATIENT_ID,COUNT(*) CNT,MAX(ADMISSION_TIME)::DATE LAST_DATE
 FROM {{ ref('encounter') }} GROUP BY PATIENT_ID
),
D AS (
 SELECT PATIENT_ID,COUNT(*) CNT FROM {{ ref('diagnosis') }} GROUP BY PATIENT_ID
),
MP AS (
 SELECT PATIENT_ID,COUNT(*) CNT FROM {{ ref('medical_procedure') }} GROUP BY PATIENT_ID
),
M AS (
 SELECT PATIENT_ID,COUNT(*) CNT FROM {{ ref('medication') }} GROUP BY PATIENT_ID
),
C AS (
 SELECT PATIENT_ID,SUM(CLAIM_AMOUNT) CLAIM_TOTAL,SUM(APPROVED_AMOUNT) APPROVED_TOTAL
 FROM {{ ref('claim') }} GROUP BY PATIENT_ID
),
L AS (
 SELECT PATIENT_ID,COUNT_IF(ABNORMAL_FLAG IN ('HIGH','LOW')) ABNORMAL_CNT
 FROM {{ ref('lab_result') }} GROUP BY PATIENT_ID
)
SELECT
 P.PATIENT_ID,
 TRIM(P.FIRST_NAME || ' ' || P.LAST_NAME),
 DATEDIFF('YEAR',P.DATE_OF_BIRTH,CURRENT_DATE()),
 P.GENDER,
 COALESCE(E.CNT,0),
 COALESCE(D.CNT,0),
 COALESCE(MP.CNT,0),
 COALESCE(M.CNT,0),
 COALESCE(C.CLAIM_TOTAL,0),
 COALESCE(C.APPROVED_TOTAL,0),
 E.LAST_DATE,
 LEAST(100,COALESCE(D.CNT,0)*5 + COALESCE(L.ABNORMAL_CNT,0)*2),
 CURRENT_TIMESTAMP()
FROM {{ ref('patient') }} P
LEFT JOIN E ON E.PATIENT_ID=P.PATIENT_ID
LEFT JOIN D ON D.PATIENT_ID=P.PATIENT_ID
LEFT JOIN MP ON MP.PATIENT_ID=P.PATIENT_ID
LEFT JOIN M ON M.PATIENT_ID=P.PATIENT_ID
LEFT JOIN C ON C.PATIENT_ID=P.PATIENT_ID
LEFT JOIN L ON L.PATIENT_ID=P.PATIENT_ID
)
select * from converted_result
