-- Converted from GOLD.SP_BUILD_CLAIM_ANALYTICS.
with converted_result (REPORT_MONTH, PAYER_NAME, TOTAL_CLAIMS, SUBMITTED_AMOUNT, APPROVED_AMOUNT, PATIENT_AMOUNT, APPROVAL_RATE, REFRESHED_AT) as (
SELECT DATE_TRUNC('MONTH',CLAIM_DATE)::DATE,PAYER_NAME,COUNT(*),
       COALESCE(SUM(CLAIM_AMOUNT),0),COALESCE(SUM(APPROVED_AMOUNT),0),
       COALESCE(SUM(PATIENT_PAY_AMOUNT),0),
       ROUND(100*SUM(APPROVED_AMOUNT)/NULLIF(SUM(CLAIM_AMOUNT),0),2),
       CURRENT_TIMESTAMP()
FROM {{ ref('claim') }}
GROUP BY DATE_TRUNC('MONTH',CLAIM_DATE),PAYER_NAME
)
select * from converted_result
