-- Converted from GOLD.SP_BUILD_PROVIDER_KPI.
with converted_result (PROVIDER_ID, PROVIDER_NAME, SPECIALITY, TOTAL_PATIENTS, TOTAL_ENCOUNTERS, TOTAL_PROCEDURES, AVG_LENGTH_OF_STAY, TOTAL_REVENUE, REFRESHED_AT) as (
WITH E AS (
 SELECT PROVIDER_ID,COUNT(DISTINCT PATIENT_ID) TOTAL_PATIENTS,COUNT(*) TOTAL_ENCOUNTERS,AVG(LENGTH_OF_STAY) AVG_LOS
 FROM {{ ref('encounter') }} GROUP BY PROVIDER_ID
),
MP AS (
 SELECT PROVIDER_ID,COUNT(*) TOTAL_PROCEDURES FROM {{ ref('medical_procedure') }} GROUP BY PROVIDER_ID
),
REV AS (
 SELECT E.PROVIDER_ID,SUM(C.APPROVED_AMOUNT) TOTAL_REVENUE
 FROM {{ ref('encounter') }} E JOIN {{ ref('claim') }} C ON C.ENCOUNTER_ID=E.ENCOUNTER_ID
 GROUP BY E.PROVIDER_ID
)
SELECT P.PROVIDER_ID,P.PROVIDER_NAME,P.SPECIALITY,
       COALESCE(E.TOTAL_PATIENTS,0),COALESCE(E.TOTAL_ENCOUNTERS,0),COALESCE(MP.TOTAL_PROCEDURES,0),
       COALESCE(E.AVG_LOS,0),COALESCE(REV.TOTAL_REVENUE,0),CURRENT_TIMESTAMP()
FROM {{ ref('provider') }} P
LEFT JOIN E ON E.PROVIDER_ID=P.PROVIDER_ID
LEFT JOIN MP ON MP.PROVIDER_ID=P.PROVIDER_ID
LEFT JOIN REV ON REV.PROVIDER_ID=P.PROVIDER_ID
)
select * from converted_result
