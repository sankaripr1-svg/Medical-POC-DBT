-- Converted from GOLD.SP_BUILD_READMISSION_KPI.
with converted_result (FACILITY_ID, REPORT_MONTH, DISCHARGED_ENCOUNTERS, READMITTED_30_DAY, READMISSION_RATE, REFRESHED_AT) as (
WITH X AS (
 SELECT FACILITY_ID,PATIENT_ID,ADMISSION_TIME,DISCHARGE_TIME,
        LEAD(ADMISSION_TIME) OVER(PARTITION BY PATIENT_ID ORDER BY ADMISSION_TIME) NEXT_ADMISSION
 FROM {{ ref('encounter') }}
 WHERE DISCHARGE_TIME IS NOT NULL
)
SELECT FACILITY_ID,DATE_TRUNC('MONTH',DISCHARGE_TIME)::DATE,
       COUNT(*),
       COUNT_IF(DATEDIFF('DAY',DISCHARGE_TIME,NEXT_ADMISSION) BETWEEN 0 AND 30),
       ROUND(100*COUNT_IF(DATEDIFF('DAY',DISCHARGE_TIME,NEXT_ADMISSION) BETWEEN 0 AND 30)
                 /NULLIF(COUNT(*),0),2),
       CURRENT_TIMESTAMP()
FROM X
GROUP BY FACILITY_ID,DATE_TRUNC('MONTH',DISCHARGE_TIME)
)
select * from converted_result
