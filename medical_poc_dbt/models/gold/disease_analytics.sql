with converted_result (ICD10_CODE, DIAGNOSIS_NAME, UNIQUE_PATIENTS, TOTAL_CASES, AVG_PATIENT_AGE, MALE_CASES, FEMALE_CASES, REFRESHED_AT) as (
SELECT D.ICD10_CODE,D.DIAGNOSIS_NAME,
       COUNT(DISTINCT D.PATIENT_ID),COUNT(*),
       AVG(DATEDIFF('YEAR',P.DATE_OF_BIRTH,D.DIAGNOSIS_DATE)),
       COUNT_IF(P.GENDER='MALE'),COUNT_IF(P.GENDER='FEMALE'),
       CURRENT_TIMESTAMP()
FROM {{ ref('diagnosis') }} D
LEFT JOIN {{ ref('patient') }} P ON P.PATIENT_ID=D.PATIENT_ID
GROUP BY D.ICD10_CODE,D.DIAGNOSIS_NAME
)
select * from converted_result
