CREATE OR REPLACE PROCEDURE BRONZE.SP_API_LOAD_CLAIMS(
    P_PAYLOAD VARIANT, P_SOURCE_SYSTEM VARCHAR, P_BATCH_ID VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE V_COUNT NUMBER;
BEGIN
    INSERT INTO BRONZE.RAW_CLAIM
      (SOURCE_SYSTEM,BATCH_ID,CLAIM_ID,RAW_PAYLOAD,RECORD_HASH)
    SELECT :P_SOURCE_SYSTEM,:P_BATCH_ID,VALUE:claim_id::VARCHAR,VALUE,SHA2(TO_JSON(VALUE),256)
    FROM TABLE(FLATTEN(INPUT => :P_PAYLOAD));
    V_COUNT := SQLROWCOUNT;
    RETURN 'CLAIM records loaded: ' || V_COUNT;
END;
$$;
