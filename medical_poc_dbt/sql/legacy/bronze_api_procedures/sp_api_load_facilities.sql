CREATE OR REPLACE PROCEDURE BRONZE.SP_API_LOAD_FACILITIES(
    P_PAYLOAD VARIANT, P_SOURCE_SYSTEM VARCHAR, P_BATCH_ID VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE V_COUNT NUMBER;
BEGIN
    INSERT INTO BRONZE.RAW_FACILITY
      (SOURCE_SYSTEM,BATCH_ID,FACILITY_ID,RAW_PAYLOAD,RECORD_HASH)
    SELECT :P_SOURCE_SYSTEM,:P_BATCH_ID,VALUE:facility_id::VARCHAR,VALUE,SHA2(TO_JSON(VALUE),256)
    FROM TABLE(FLATTEN(INPUT => :P_PAYLOAD));
    V_COUNT := SQLROWCOUNT;
    RETURN 'FACILITY records loaded: ' || V_COUNT;
END;
$$;
