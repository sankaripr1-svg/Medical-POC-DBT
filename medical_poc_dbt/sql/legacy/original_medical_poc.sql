 (SELECT COUNT(*) FROM SILVER.PATIENT WHERE ACTIVE_FLAG=TRUE),
 (SELECT COUNT(*) FROM SILVER.ENCOUNTER WHERE ADMISSION_TIME::DATE=CURRENT_DATE()),
 (SELECT COUNT(*) FROM SILVER.ENCOUNTER WHERE ADMISSION_TIME::DATE=CURRENT_DATE() AND ENCOUNTER_TYPE='INPATIENT'),
