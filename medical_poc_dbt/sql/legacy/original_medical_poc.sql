 (SELECT COUNT(*) FROM SILVER.MEDICAL_PROCEDURE WHERE PROCEDURE_DATE=CURRENT_DATE()),
 (SELECT COUNT(*) FROM SILVER.CLAIM WHERE CLAIM_DATE=CURRENT_DATE()),
 (SELECT COALESCE(SUM(CLAIM_AMOUNT),0) FROM SILVER.CLAIM WHERE CLAIM_DATE=CURRENT_DATE()),
 (SELECT COUNT(*) FROM SILVER.LAB_RESULT WHERE RESULTED_AT::DATE=CURRENT_DATE() AND ABNORMAL_FLAG IN ('HIGH','LOW')),
 CURRENT_TIMESTAMP();

