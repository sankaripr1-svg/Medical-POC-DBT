CREATE OR REPLACE PROCEDURE BRONZE.SP_BRONZE_DEDUP_PATIENT()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
    DELETE FROM BRONZE.RAW_PATIENT
    WHERE RAW_ID IN (
      SELECT RAW_ID FROM (
        SELECT RAW_ID,
               ROW_NUMBER() OVER(PARTITION BY PATIENT_ID,RECORD_HASH ORDER BY INGESTED_AT DESC,RAW_ID DESC) RN
        FROM BRONZE.RAW_PATIENT
      ) WHERE RN > 1
    );
    RETURN 'Patient duplicate rows deleted: ' || SQLROWCOUNT;
END;
$$;

CREATE OR REPLACE PROCEDURE BRONZE.SP_BRONZE_DEDUP_ENCOUNTER()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
    DELETE FROM BRONZE.RAW_ENCOUNTER
    WHERE RAW_ID IN (
      SELECT RAW_ID FROM (
        SELECT RAW_ID,
               ROW_NUMBER() OVER(PARTITION BY ENCOUNTER_ID,RECORD_HASH ORDER BY INGESTED_AT DESC,RAW_ID DESC) RN
        FROM BRONZE.RAW_ENCOUNTER
      ) WHERE RN > 1
    );
    RETURN 'Encounter duplicate rows deleted: ' || SQLROWCOUNT;
END;
$$;

CREATE OR REPLACE PROCEDURE BRONZE.SP_BRONZE_ARCHIVE(P_RETENTION_DAYS NUMBER DEFAULT 180)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE V_TOTAL NUMBER DEFAULT 0;
BEGIN
    DELETE FROM BRONZE.RAW_PATIENT WHERE INGESTED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
    V_TOTAL := V_TOTAL + SQLROWCOUNT;
    DELETE FROM BRONZE.RAW_PROVIDER WHERE INGESTED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
    V_TOTAL := V_TOTAL + SQLROWCOUNT;
    DELETE FROM BRONZE.RAW_FACILITY WHERE INGESTED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
    V_TOTAL := V_TOTAL + SQLROWCOUNT;
    DELETE FROM BRONZE.RAW_ENCOUNTER WHERE INGESTED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
    V_TOTAL := V_TOTAL + SQLROWCOUNT;
    DELETE FROM BRONZE.RAW_DIAGNOSIS WHERE INGESTED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
    V_TOTAL := V_TOTAL + SQLROWCOUNT;
    DELETE FROM BRONZE.RAW_MEDICAL_PROCEDURE WHERE INGESTED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
    V_TOTAL := V_TOTAL + SQLROWCOUNT;
    DELETE FROM BRONZE.RAW_CLAIM WHERE INGESTED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
    V_TOTAL := V_TOTAL + SQLROWCOUNT;
    DELETE FROM BRONZE.RAW_LAB_RESULT WHERE INGESTED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
    V_TOTAL := V_TOTAL + SQLROWCOUNT;
    DELETE FROM BRONZE.RAW_MEDICATION WHERE INGESTED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
    V_TOTAL := V_TOTAL + SQLROWCOUNT;
    RETURN 'Bronze retention cleanup deleted rows: ' || V_TOTAL;
END;
$$;

