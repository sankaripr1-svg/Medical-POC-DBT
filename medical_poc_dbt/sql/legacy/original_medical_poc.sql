CREATE OR REPLACE PROCEDURE GOLD.SP_BUILD_PROVIDER_KPI()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
TRUNCATE TABLE GOLD.PROVIDER_KPI;
INSERT INTO GOLD.PROVIDER_KPI
WITH E AS (
 SELECT PROVIDER_ID,COUNT(DISTINCT PATIENT_ID) TOTAL_PATIENTS,COUNT(*) TOTAL_ENCOUNTERS,AVG(LENGTH_OF_STAY) AVG_LOS
 FROM SILVER.ENCOUNTER GROUP BY PROVIDER_ID
),
MP AS (
 SELECT PROVIDER_ID,COUNT(*) TOTAL_PROCEDURES FROM SILVER.MEDICAL_PROCEDURE GROUP BY PROVIDER_ID
),
REV AS (
 SELECT E.PROVIDER_ID,SUM(C.APPROVED_AMOUNT) TOTAL_REVENUE
 FROM SILVER.ENCOUNTER E JOIN SILVER.CLAIM C ON C.ENCOUNTER_ID=E.ENCOUNTER_ID
 GROUP BY E.PROVIDER_ID
)
SELECT P.PROVIDER_ID,P.PROVIDER_NAME,P.SPECIALITY,
       COALESCE(E.TOTAL_PATIENTS,0),COALESCE(E.TOTAL_ENCOUNTERS,0),COALESCE(MP.TOTAL_PROCEDURES,0),
       COALESCE(E.AVG_LOS,0),COALESCE(REV.TOTAL_REVENUE,0),CURRENT_TIMESTAMP()
FROM SILVER.PROVIDER P
LEFT JOIN E ON E.PROVIDER_ID=P.PROVIDER_ID
LEFT JOIN MP ON MP.PROVIDER_ID=P.PROVIDER_ID
LEFT JOIN REV ON REV.PROVIDER_ID=P.PROVIDER_ID;
RETURN 'GOLD.PROVIDER_KPI refreshed: ' || SQLROWCOUNT;
END;
$$;

CREATE OR REPLACE PROCEDURE GOLD.SP_BUILD_FACILITY_KPI()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
TRUNCATE TABLE GOLD.FACILITY_KPI;
INSERT INTO GOLD.FACILITY_KPI
WITH E AS (
 SELECT FACILITY_ID,COUNT(DISTINCT PATIENT_ID) TOTAL_PATIENTS,
        COUNT_IF(ENCOUNTER_TYPE='INPATIENT') TOTAL_ADMISSIONS,
        AVG(LENGTH_OF_STAY) AVG_LOS
 FROM SILVER.ENCOUNTER GROUP BY FACILITY_ID
),
CL AS (
 SELECT E.FACILITY_ID,SUM(C.APPROVED_AMOUNT) TOTAL_APPROVED
 FROM SILVER.ENCOUNTER E JOIN SILVER.CLAIM C ON C.ENCOUNTER_ID=E.ENCOUNTER_ID
 GROUP BY E.FACILITY_ID
),
PR AS (
 SELECT E.FACILITY_ID,COUNT(*) TOTAL_PROCEDURES
 FROM SILVER.MEDICAL_PROCEDURE P JOIN SILVER.ENCOUNTER E ON E.ENCOUNTER_ID=P.ENCOUNTER_ID
 GROUP BY E.FACILITY_ID
)
SELECT F.FACILITY_ID,F.FACILITY_NAME,
       COALESCE(E.TOTAL_PATIENTS,0),COALESCE(E.TOTAL_ADMISSIONS,0),COALESCE(E.AVG_LOS,0),
       COALESCE(CL.TOTAL_APPROVED,0),COALESCE(PR.TOTAL_PROCEDURES,0),CURRENT_TIMESTAMP()
FROM SILVER.FACILITY F
LEFT JOIN E ON E.FACILITY_ID=F.FACILITY_ID
LEFT JOIN CL ON CL.FACILITY_ID=F.FACILITY_ID
LEFT JOIN PR ON PR.FACILITY_ID=F.FACILITY_ID;
RETURN 'GOLD.FACILITY_KPI refreshed: ' || SQLROWCOUNT;
END;
$$;

