-- BRONZE API INGESTION PROCEDURES (1-9)
-- Input P_PAYLOAD must be a JSON ARRAY.
-- Example: CALL BRONZE.SP_API_LOAD_PATIENTS(PARSE_JSON('[{...},{...}]'), ...);
-- =====================================================================

CREATE OR REPLACE PROCEDURE BRONZE.SP_API_LOAD_PATIENTS(
    P_PAYLOAD VARIANT, P_SOURCE_SYSTEM VARCHAR, P_BATCH_ID VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE V_COUNT NUMBER;
BEGIN
    INSERT INTO BRONZE.RAW_PATIENT
      (SOURCE_SYSTEM,BATCH_ID,PATIENT_ID,RAW_PAYLOAD,RECORD_HASH)
    SELECT :P_SOURCE_SYSTEM,:P_BATCH_ID,
           VALUE:patient_id::VARCHAR,
           VALUE,
           SHA2(TO_JSON(VALUE),256)
    FROM TABLE(FLATTEN(INPUT => :P_PAYLOAD));

    V_COUNT := SQLROWCOUNT;
    INSERT INTO CONTROL.API_EXECUTION_LOG
      (API_NAME,BATCH_ID,SOURCE_SYSTEM,START_TIME,END_TIME,RECORD_COUNT,RUN_STATUS)
    VALUES ('PATIENT',:P_BATCH_ID,:P_SOURCE_SYSTEM,CURRENT_TIMESTAMP(),CURRENT_TIMESTAMP(),:V_COUNT,'SUCCESS');
    RETURN 'PATIENT records loaded: ' || V_COUNT;
END;
$$;

