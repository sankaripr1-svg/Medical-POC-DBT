CREATE OR REPLACE PROCEDURE CONTROL.SP_RUN_MEDICAL_TRANSFORM_PIPELINE()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_START TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP();
BEGIN
  CALL BRONZE.SP_BRONZE_DEDUP_PATIENT();
  CALL BRONZE.SP_BRONZE_DEDUP_ENCOUNTER();

  CALL SILVER.SP_LOAD_PATIENT();
  CALL SILVER.SP_LOAD_PROVIDER();
  CALL SILVER.SP_LOAD_FACILITY();
  CALL SILVER.SP_LOAD_ENCOUNTER();
  CALL SILVER.SP_LOAD_DIAGNOSIS();
  CALL SILVER.SP_LOAD_MEDICAL_PROCEDURE();
  CALL SILVER.SP_LOAD_CLAIM();
  CALL SILVER.SP_LOAD_LAB_RESULT();
  CALL SILVER.SP_LOAD_MEDICATION();

  CALL SILVER.SP_VALIDATE_PATIENT();
  CALL SILVER.SP_VALIDATE_ENCOUNTER();
  CALL SILVER.SP_VALIDATE_CLAIMS();
  CALL SILVER.SP_VALIDATE_LABS();

  CALL GOLD.SP_BUILD_PATIENT_360();
  CALL GOLD.SP_BUILD_DISEASE_ANALYTICS();
  CALL GOLD.SP_BUILD_PROCEDURE_ANALYTICS();
  CALL GOLD.SP_BUILD_PROVIDER_KPI();
  CALL GOLD.SP_BUILD_FACILITY_KPI();
  CALL GOLD.SP_BUILD_CLAIM_ANALYTICS();
  CALL GOLD.SP_BUILD_READMISSION_KPI();
  CALL GOLD.SP_BUILD_DAILY_SUMMARY();
  CALL GOLD.SP_BUILD_ABNORMAL_LAB_KPI();

  INSERT INTO CONTROL.ETL_AUDIT_LOG
    (PROCEDURE_NAME,LAYER_NAME,SOURCE_TABLE,TARGET_TABLE,START_TIME,END_TIME,STATUS)
  VALUES
    ('SP_RUN_MEDICAL_TRANSFORM_PIPELINE','ALL','BRONZE','GOLD',:V_START,CURRENT_TIMESTAMP(),'SUCCESS');

  RETURN 'Bronze -> Silver -> Gold pipeline completed successfully';
EXCEPTION
  WHEN OTHER THEN
    INSERT INTO CONTROL.ETL_AUDIT_LOG
      (PROCEDURE_NAME,LAYER_NAME,SOURCE_TABLE,TARGET_TABLE,START_TIME,END_TIME,STATUS,ERROR_MESSAGE)
    VALUES
      ('SP_RUN_MEDICAL_TRANSFORM_PIPELINE','ALL','BRONZE','GOLD',:V_START,CURRENT_TIMESTAMP(),'FAILED',SQLERRM);
    RETURN 'Pipeline failed: ' || SQLERRM;
END;
$$;

CREATE OR REPLACE PROCEDURE CONTROL.SP_PURGE_OLD_AUDIT(P_RETENTION_DAYS NUMBER DEFAULT 730)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE V_COUNT NUMBER DEFAULT 0;
BEGIN
  DELETE FROM CONTROL.ETL_AUDIT_LOG
   WHERE CREATED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
  V_COUNT := V_COUNT + SQLROWCOUNT;

  DELETE FROM CONTROL.API_EXECUTION_LOG
   WHERE CREATED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
  V_COUNT := V_COUNT + SQLROWCOUNT;

  DELETE FROM CONTROL.DATA_QUALITY_ERROR
   WHERE CREATED_AT < DATEADD(DAY,-:P_RETENTION_DAYS,CURRENT_TIMESTAMP());
  V_COUNT := V_COUNT + SQLROWCOUNT;

  RETURN 'Old control/audit rows deleted: ' || V_COUNT;
END;
$$;

