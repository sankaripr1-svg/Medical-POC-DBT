CREATE OR REPLACE PROCEDURE GOLD.SP_BUILD_PATIENT_360()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
TRUNCATE TABLE GOLD.PATIENT_360;

INSERT INTO GOLD.PATIENT_360
WITH E AS (
 SELECT PATIENT_ID,COUNT(*) CNT,MAX(ADMISSION_TIME)::DATE LAST_DATE
 FROM SILVER.ENCOUNTER GROUP BY PATIENT_ID
),
D AS (
 SELECT PATIENT_ID,COUNT(*) CNT FROM SILVER.DIAGNOSIS GROUP BY PATIENT_ID
),
MP AS (
 SELECT PATIENT_ID,COUNT(*) CNT FROM SILVER.MEDICAL_PROCEDURE GROUP BY PATIENT_ID
),
M AS (
 SELECT PATIENT_ID,COUNT(*) CNT FROM SILVER.MEDICATION GROUP BY PATIENT_ID
),
C AS (
 SELECT PATIENT_ID,SUM(CLAIM_AMOUNT) CLAIM_TOTAL,SUM(APPROVED_AMOUNT) APPROVED_TOTAL
 FROM SILVER.CLAIM GROUP BY PATIENT_ID
),
L AS (
 SELECT PATIENT_ID,COUNT_IF(ABNORMAL_FLAG IN ('HIGH','LOW')) ABNORMAL_CNT
 FROM SILVER.LAB_RESULT GROUP BY PATIENT_ID
)
SELECT
 P.PATIENT_ID,
 TRIM(P.FIRST_NAME || ' ' || P.LAST_NAME),
 DATEDIFF('YEAR',P.DATE_OF_BIRTH,CURRENT_DATE()),
 P.GENDER,
 COALESCE(E.CNT,0),
 COALESCE(D.CNT,0),
 COALESCE(MP.CNT,0),
 COALESCE(M.CNT,0),
 COALESCE(C.CLAIM_TOTAL,0),
 COALESCE(C.APPROVED_TOTAL,0),
 E.LAST_DATE,
 LEAST(100,COALESCE(D.CNT,0)*5 + COALESCE(L.ABNORMAL_CNT,0)*2),
 CURRENT_TIMESTAMP()
FROM SILVER.PATIENT P
LEFT JOIN E ON E.PATIENT_ID=P.PATIENT_ID
LEFT JOIN D ON D.PATIENT_ID=P.PATIENT_ID
LEFT JOIN MP ON MP.PATIENT_ID=P.PATIENT_ID
LEFT JOIN M ON M.PATIENT_ID=P.PATIENT_ID
LEFT JOIN C ON C.PATIENT_ID=P.PATIENT_ID
LEFT JOIN L ON L.PATIENT_ID=P.PATIENT_ID;

